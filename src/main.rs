fn set_pstate(level_id: &str, label: &str) -> Result<String, String> {
    let pstate_path = "/sys/kernel/debug/dri/0/pstate";
    if !Path::new(pstate_path).exists() {
        return Err("⚠ To change GPU speed, run: sudo nouveau-boost".into());
    }
    fs::write(pstate_path, format!("{}\n", level_id))
        .map_err(|e| format!("Could not switch to {}: {}", label, e))?;
    Ok(format!("🚀 GPU speed switched to: {}!", label))
}

fn run_tui() -> io::Result<()> {
    enable_raw_mode()?;
    stdout().execute(EnterAlternateScreen)?;
    let mut terminal = Terminal::new(CrosstermBackend::new(stdout()))?;

    let mut telemetry = collect_telemetry();
    let mut temp_history: Vec<u64> = vec![telemetry.temp_c as u64; 60];
    let mut status_msg = String::from(
        "👉 PRESS: [1] Auto-Fix My GPU (1-Click) | [2] Fast Mode (Turbo) | [3] Quiet Mode | [q] Quit",
    );
    let mut last_tick = Instant::now();

    loop {
        terminal.draw(|f| {
            let area = f.area();
            let chunks = Layout::default()
                .direction(Direction::Vertical)
                .constraints([
                    Constraint::Length(3),
                    Constraint::Length(10),
                    Constraint::Length(5),
                    Constraint::Min(10),
                    Constraint::Length(3),
                ])
                .split(area);

            let is_healthy = telemetry.glamor_accel && telemetry.all_fw_present && telemetry.browser_vaapi_tuned;

            // Beginner-friendly header
            let header = Paragraph::new(Line::from(vec![
                Span::styled(
                    if is_healthy { " ✔ GPU HEALTHY & OPTIMIZED " } else { " ⚠ NEEDS OPTIMIZATION (PRESS 1) " },
                    Style::default()
                        .fg(Color::Black)
                        .bg(if is_healthy { Color::Green } else { Color::Yellow })
                        .add_modifier(Modifier::BOLD),
                ),
                Span::raw(" "),
                Span::styled(
                    format!("GPU: {} · VRAM: {}", telemetry.chip_name, telemetry.vram_mib),
                    Style::default().fg(Color::Cyan).add_modifier(Modifier::BOLD),
                ),
            ]))
            .block(Block::default().borders(Borders::ALL).title(" ⚡ Nouveau-Boost · Easy Legacy NVIDIA Optimizer for Linux (by Munique Feitoza · GPL-2.0) "));
            f.render_widget(header, chunks[0]);

            // Summary + Thermometer
            let top_row = Layout::default()
                .direction(Direction::Horizontal)
                .constraints([Constraint::Percentage(52), Constraint::Percentage(48)])
                .split(chunks[1]);

            let hw_rows = vec![
                Row::new(vec![Cell::from("Detected GPU"), Cell::from(format!("{} ({})", telemetry.chip_name, telemetry.codename))]),
                Row::new(vec![Cell::from("Video Memory"), Cell::from(telemetry.vram_mib.clone())]),
                Row::new(vec![
                    Cell::from("3D Acceleration"),
                    Cell::from(if telemetry.glamor_accel { "✔ ON (Fast)" } else { "✖ OFF (Slow - Press 1)" })
                        .style(Style::default().fg(if telemetry.glamor_accel { Color::Green } else { Color::Red })),
                ]),
                Row::new(vec![
                    Cell::from("Video Anti-Freeze"),
                    Cell::from(if telemetry.all_fw_present && telemetry.browser_vaapi_tuned {
                        "✔ PROTECTED (YouTube/Netflix OK)"
                    } else {
                        "⚠ UNPROTECTED (Press 1)"
                    })
                    .style(Style::default().fg(if telemetry.all_fw_present && telemetry.browser_vaapi_tuned {
                        Color::Green
                    } else {
                        Color::Yellow
                    })),
                ]),
                Row::new(vec![
                    Cell::from("Current Speed"),
                    Cell::from(telemetry.active_pstate.clone()).style(Style::default().fg(Color::Cyan)),
                ]),
            ];
            let hw_table = Table::new(hw_rows, [Constraint::Length(18), Constraint::Min(25)])
                .block(Block::default().borders(Borders::ALL).title(" 📊 Your Graphics Card Summary "));
            f.render_widget(hw_table, top_row[0]);

            let gauges_layout = Layout::default()
                .direction(Direction::Vertical)
                .constraints([Constraint::Length(3), Constraint::Length(3), Constraint::Min(2)])
                .split(top_row[1]);

            let temp_ratio = (telemetry.temp_c / telemetry.temp_max_c).clamp(0.0, 1.0);
            let (temp_color, temp_status) = if telemetry.temp_c < 60.0 {
                (Color::Green, "Cool / Great")
            } else if telemetry.temp_c < 80.0 {
                (Color::Yellow, "Warm / Normal")
            } else {
                (Color::Red, "Hot!")
            };
            let temp_gauge = Gauge::default()
                .block(Block::default().borders(Borders::ALL).title(" 🌡️ GPU Temperature "))
                .gauge_style(Style::default().fg(temp_color))
                .ratio(temp_ratio)
                .label(format!("{:.1} °C ({}) — Safe Limit: {:.0} °C", telemetry.temp_c, temp_status, telemetry.temp_max_c));
            f.render_widget(temp_gauge, gauges_layout[0]);

            let fan_gauge = Gauge::default()
                .block(Block::default().borders(Borders::ALL).title(" 🌀 Cooling Fan & Core Power "))
                .gauge_style(Style::default().fg(Color::Cyan))
                .percent(telemetry.fan_pwm.min(100) as u16)
                .label(format!("Fan: {}% ({}) | Core: {} mV", telemetry.fan_pwm, telemetry.fan_mode, telemetry.core_mv));
            f.render_widget(fan_gauge, gauges_layout[1]);

            let fw_spans: Vec<Span> = telemetry
                .falcon_fw_files
                .iter()
                .flat_map(|(name, ok)| {
                    vec![
                        Span::styled(
                            format!(" {} {} ", if *ok { "✔" } else { "✖" }, name),
                            Style::default().fg(if *ok { Color::Green } else { Color::Red }).add_modifier(Modifier::BOLD),
                        ),
                        Span::raw(" "),
                    ]
                })
                .collect();
            let fw_box = Paragraph::new(Line::from(fw_spans))
                .block(Block::default().borders(Borders::ALL).title(" 🎬 Installed Video Engines (Falcon) "));
            f.render_widget(fw_box, gauges_layout[2]);

            // Temperature History
            let spark = Sparkline::default()
                .block(Block::default().borders(Borders::ALL).title(" 📈 Temperature History (Last 60 Seconds) "))
                .data(&temp_history)
                .max(100)
                .style(Style::default().fg(Color::Magenta));
            f.render_widget(spark, chunks[2]);

            // Plain-English Doctor
            let items: Vec<ListItem> = telemetry
                .kernel_anomalies
                .iter()
                .map(|a| {
                    let badge_color = match a.severity {
                        "ALL GOOD" => Color::Green,
                        "KERNEL INFO" => Color::Cyan,
                        _ => Color::Yellow,
                    };
                    ListItem::new(vec![
                        Line::from(vec![
                            Span::styled(
                                format!(" [{}] ", a.severity),
                                Style::default().fg(Color::Black).bg(badge_color).add_modifier(Modifier::BOLD),
                            ),
                            Span::raw(" "),
                            Span::styled(&a.title, Style::default().fg(Color::White).add_modifier(Modifier::BOLD)),
                        ]),
                        Line::from(Span::styled(format!("    • What it means : {}", a.simple_explanation), Style::default().fg(Color::Gray))),
                        Line::from(Span::styled(format!("    • How to fix    : {}", a.action_text), Style::default().fg(Color::Yellow))),
                    ])
                })
                .collect();

            let doctor_list = List::new(items)
                .block(Block::default().borders(Borders::ALL).title(" 🩺 Easy Health Check (Plain English — No Linux Knowledge Needed) "));
            f.render_widget(doctor_list, chunks[3]);

            // Footer Action Bar
            let footer = Paragraph::new(status_msg.as_str())
                .style(Style::default().fg(Color::Black).bg(Color::Yellow).add_modifier(Modifier::BOLD))
                .block(Block::default().borders(Borders::ALL))
                .wrap(Wrap { trim: true });
            f.render_widget(footer, chunks[4]);
        })?;

        if event::poll(Duration::from_millis(250))? {
            if let Event::Key(key) = event::read()? {
                if key.kind == KeyEventKind::Press {
                    match key.code {
                        KeyCode::Char('q') | KeyCode::Esc => break,
                        KeyCode::Char('1') | KeyCode::Char('f') => {
                            let res = auto_fix_system();
                            status_msg = res.join("  |  ");
                            telemetry = collect_telemetry();
                        }
                        KeyCode::Char('2') | KeyCode::Char('p') => {
                            status_msg = match set_pstate("0f", "Fast Mode (Max Performance)") {
                                Ok(m) => m,
                                Err(e) => e,
                            };
                            telemetry = collect_telemetry();
                        }
                        KeyCode::Char('3') | KeyCode::Char('e') => {
                            status_msg = match set_pstate("07", "Quiet / Eco Mode") {
                                Ok(m) => m,
                                Err(e) => e,
                            };
                            telemetry = collect_telemetry();
                        }
                        KeyCode::Char('r') => {
                            telemetry = collect_telemetry();
                            status_msg = "✔ Refreshed! Press [1] Auto-Fix My GPU | [2] Fast Mode | [3] Quiet Mode | [q] Quit".into();
                        }
                        _ => {}
                    }
                }
            }
        }

        if last_tick.elapsed() >= Duration::from_secs(1) {
            telemetry = collect_telemetry();
            temp_history.push(telemetry.temp_c as u64);
            if temp_history.len() > 60 {
                temp_history.remove(0);
            }
            last_tick = Instant::now();
        }
    }

    disable_raw_mode()?;
    stdout().execute(LeaveAlternateScreen)?;
    Ok(())
}

fn main() {
    let args: Vec<String> = env::args().collect();
    if args.iter().any(|a| a == "--report" || a == "-r") {
        let t = collect_telemetry();
        print_cli_report(&t);
        return;
    }
    if args.iter().any(|a| a == "--fix" || a == "-f") {
        println!("⚡ Auto-fixing your NVIDIA GPU configuration...");
        for msg in auto_fix_system() {
            println!("  {}", msg);
        }
        return;
    }

    if let Err(e) = run_tui() {
        eprintln!("Error opening dashboard: {}", e);
    }
}
