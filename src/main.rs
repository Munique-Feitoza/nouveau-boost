fn read_trimmed(path: impl AsRef<Path>) -> Option<String> {
    fs::read_to_string(path).ok().map(|s| s.trim().to_string())
}

fn find_nouveau_hwmon() -> Option<PathBuf> {
    let entries = fs::read_dir("/sys/class/hwmon").ok()?;
    for entry in entries.flatten() {
        let path = entry.path();
        if read_trimmed(path.join("name")).as_deref() == Some("nouveau") {
            return Some(path);
        }
    }
    None
}

fn check_firefox_vaapi_tuned() -> bool {
    let home = env::var("SUDO_USER")
        .ok()
        .map(|u| format!("/home/{}", u))
        .or_else(|| env::var("HOME").ok())
        .unwrap_or_default();

    let roots = [
        format!("{}/.config/mozilla/firefox", home),
        format!("{}/.mozilla/firefox", home),
    ];

    for root in roots {
        if let Ok(entries) = fs::read_dir(&root) {
            for entry in entries.flatten() {
                let user_js = entry.path().join("user.js");
                if let Some(content) = read_trimmed(&user_js) {
                    if content.contains("media.ffmpeg.vaapi.enabled") && content.contains("media.av1.enabled") {
                        return true;
                    }
                }
            }
        }
    }
    false
}

/// Automatically extracts and installs NVIDIA Falcon video firmware if missing
fn install_falcon_firmware_if_missing() -> Result<String, String> {
    let fw_dir = Path::new("/lib/firmware/nouveau");
    if fw_dir.join("nvc1_fuc084").exists()
        || fw_dir.join("nv98_fuc084").exists()
        || fw_dir.join("nve0_fuc084").exists()
    {
        return Ok("✔ NVIDIA Video Firmware (Falcon) is already installed!".into());
    }

    let script = r#"
set -e
TMP_DIR=$(mktemp -d)
cd "$TMP_DIR"
curl -sL -o extract_firmware.py https://raw.githubusercontent.com/imirkin/re-vp2/master/extract_firmware.py
curl -sL -o NVIDIA-340.108.run https://us.download.nvidia.com/XFree86/Linux-x86_64/340.108/NVIDIA-Linux-x86_64-340.108.run
sh NVIDIA-340.108.run --extract-only >/dev/null 2>&1
python3 extract_firmware.py >/dev/null 2>&1
sudo mkdir -p /lib/firmware/nouveau
sudo cp -f nv* vuc-* /lib/firmware/nouveau/ 2>/dev/null || true
rm -rf "$TMP_DIR"
"#;

    let status = Command::new("bash")
        .arg("-c")
        .arg(script)
        .status()
        .map_err(|e| format!("Failed to run firmware installer: {}", e))?;

    if status.success() {
        Ok("✔ Downloaded and installed NVIDIA video firmware automatically!".into())
    } else {
        Err("⚠ Run `sudo nouveau-boost` to install missing video firmware".into())
    }
}

fn auto_fix_system() -> Vec<String> {
    let mut actions = Vec::new();
    let home = env::var("SUDO_USER")
        .ok()
        .map(|u| format!("/home/{}", u))
        .or_else(|| env::var("HOME").ok())
        .unwrap_or_default();

    // 1. Optimize Browser (Firefox) to prevent YouTube/Netflix freezes
    let roots = [
        format!("{}/.config/mozilla/firefox", home),
        format!("{}/.mozilla/firefox", home),
    ];
    let mut tuned_profiles = 0;
    for root in roots {
        if let Ok(entries) = fs::read_dir(&root) {
            for entry in entries.flatten() {
                let path = entry.path();
                if path.is_dir() && path.join("prefs.js").exists() {
                    let user_js = path.join("user.js");
                    let cfg = "// Auto-generated by Nouveau-Boost (Video Freeze Protection for Legacy NVIDIA GPUs)\n\
user_pref(\"media.ffmpeg.vaapi.enabled\", true);\n\
user_pref(\"media.av1.enabled\", false);\n\
user_pref(\"gfx.webrender.all\", true);\n\
user_pref(\"media.hardware-video-decoding.force-enabled\", true);\n";
                    if fs::write(&user_js, cfg).is_ok() {
                        tuned_profiles += 1;
                    }
                }
            }
        }
    }
    if tuned_profiles > 0 {
        actions.push(format!(
            "✔ Browser optimized ({} profile): videos now use GPU hardware without freezing your PC!",
            tuned_profiles
        ));
    }

    // 2. Ensure 3D hardware acceleration is enabled in modprobe
    let modprobe_path = Path::new("/etc/modprobe.d/nouveau.conf");
    let current_mod = read_trimmed(modprobe_path).unwrap_or_default();
    if current_mod.contains("noaccel=1") {
        let new_mod = "options nouveau noaccel=0 modeset=1\n";
        match fs::write(modprobe_path, new_mod) {
            Ok(_) => actions.push("✔ Enabled GPU 3D acceleration (reboot required to apply)".into()),
            Err(_) => actions.push("⚠ Run `sudo nouveau-boost` to enable system 3D acceleration".into()),
        }
    } else {
        actions.push("✔ GPU 3D acceleration is already active!".into());
    }

    // 3. Verify and install Falcon Video Firmware if missing
    match install_falcon_firmware_if_missing() {
        Ok(msg) => actions.push(msg),
        Err(err) => actions.push(err),
    }

    actions
}

