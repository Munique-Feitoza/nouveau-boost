fn collect_telemetry() -> GpuTelemetry {
    let dev_path = Path::new("/sys/class/drm/card0/device");
    let uevent = read_trimmed(dev_path.join("uevent")).unwrap_or_default();

    let mut pci_slot = "0000:01:00.0".to_string();
    let mut pci_id = "10DE:0F02".to_string();
    for line in uevent.lines() {
        if let Some(val) = line.strip_prefix("PCI_SLOT_NAME=") {
            pci_slot = val.to_string();
        } else if let Some(val) = line.strip_prefix("PCI_ID=") {
            pci_id = val.to_string();
        }
    }

    let pcie_speed = read_trimmed(dev_path.join("current_link_speed")).unwrap_or_else(|| "N/A".into());
    let pcie_width = read_trimmed(dev_path.join("current_link_width")).unwrap_or_else(|| "N/A".into());

    let mut temp_c = 0.0;
    let mut temp_max_c = 95.0;
    let mut temp_crit_c = 105.0;
    let mut core_mv = 0;
    let mut core_min_mv = 0;
    let mut core_max_mv = 0;
    let mut fan_pwm = 0;
    let mut fan_mode = "Automatic".to_string();

    if let Some(hwmon) = find_nouveau_hwmon() {
        if let Some(t) = read_trimmed(hwmon.join("temp1_input")).and_then(|v| v.parse::<f64>().ok()) {
            temp_c = t / 1000.0;
        }
        if let Some(t) = read_trimmed(hwmon.join("temp1_max")).and_then(|v| v.parse::<f64>().ok()) {
            temp_max_c = t / 1000.0;
        }
        if let Some(t) = read_trimmed(hwmon.join("temp1_crit")).and_then(|v| v.parse::<f64>().ok()) {
            temp_crit_c = t / 1000.0;
        }
        core_mv = read_trimmed(hwmon.join("in0_input"))
            .and_then(|v| v.parse::<u64>().ok())
            .unwrap_or(0);
        core_min_mv = read_trimmed(hwmon.join("in0_min"))
            .and_then(|v| v.parse::<u64>().ok())
            .unwrap_or(0);
        core_max_mv = read_trimmed(hwmon.join("in0_max"))
            .and_then(|v| v.parse::<u64>().ok())
            .unwrap_or(0);
        fan_pwm = read_trimmed(hwmon.join("pwm1"))
            .and_then(|v| v.parse::<u64>().ok())
            .unwrap_or(0);
        fan_mode = match read_trimmed(hwmon.join("pwm1_enable")).as_deref() {
            Some("0") => "100% Fixed".into(),
            Some("1") => "Manual".into(),
            Some("2") => "Automatic".into(),
            _ => "Automatic".into(),
        };
    }

    let klog = Command::new("journalctl")
        .args(["-b", "0", "-k", "--no-pager", "-g", "nouveau"])
        .output()
        .ok()
        .and_then(|o| String::from_utf8(o.stdout).ok())
        .unwrap_or_default();

    let mut chip_name = "GF108 (GeForce GT 730)".to_string();
    let mut bios_version = "Unknown".to_string();
    let mut vram_mib = "Unknown".to_string();
    let mut buffer_copy_engine = "M2MF (Standard)".to_string();
    let mut ce_channel_bug = false;
    let mut anomalies = Vec::new();

    for line in klog.lines() {
        if let Some(idx) = line.find("NVIDIA ") {
            chip_name = line[idx + 7..].trim().to_string();
        }
        if let Some(idx) = line.find("bios: version ") {
            bios_version = line[idx + 14..].trim().to_string();
        }
        if let Some(idx) = line.find("fb: ") {
            vram_mib = line[idx + 4..].trim().to_string();
        }
        if let Some(idx) = line.find("MM: using ") {
            buffer_copy_engine = line[idx + 10..].trim().to_string();
        }
        if line.contains("failed to create ce channel, -22") {
            ce_channel_bug = true;
        }
    }

    let (codename, arch_family, expected_fw) = map_arch_and_codename(&chip_name, &pci_id);

    let mut falcon_fw_files = Vec::new();
    let mut all_fw_present = true;
    for fw in expected_fw {
        let exists = Path::new("/lib/firmware/nouveau").join(fw).exists();
        if !exists {
            all_fw_present = false;
        }
        falcon_fw_files.push((fw.to_string(), exists));
    }

    let modprobe_cfg = read_trimmed("/etc/modprobe.d/nouveau.conf").unwrap_or_default();
    let glamor_accel = !modprobe_cfg.contains("noaccel=1") && Path::new("/dev/dri/renderD128").exists();
    let vaapi_render_node = Path::new("/dev/dri/renderD128").exists();
    let browser_vaapi_tuned = check_firefox_vaapi_tuned();

    // Plain-English, beginner-friendly diagnostics
    if glamor_accel {
        anomalies.push(KernelAnomaly {
            severity: "ALL GOOD",
            title: "GPU 3D Hardware Acceleration is ACTIVE".into(),
            simple_explanation: "Your NVIDIA graphics card is properly rendering the desktop instead of overloading your CPU.".into(),
            action_text: "No action needed.".into(),
        });
    } else {
        anomalies.push(KernelAnomaly {
            severity: "ISSUE",
            title: "Your NVIDIA Graphics Card is DISABLED (noaccel=1)".into(),
            simple_explanation: "Your PC is slow or freezing because the CPU is doing all graphics work by itself.".into(),
            action_text: "👉 Press key [1] in this app to ENABLE your graphics card automatically!".into(),
        });
    }

    if all_fw_present && browser_vaapi_tuned {
        anomalies.push(KernelAnomaly {
            severity: "ALL GOOD",
            title: "Video Freeze Protection (YouTube / Netflix / Browser) is ACTIVE".into(),
            simple_explanation: "NVIDIA video engines (Falcon) are installed and your browser is protected against heavy AV1 freezes.".into(),
            action_text: "You can watch videos smoothly without system lockups!".into(),
        });
    } else {
        anomalies.push(KernelAnomaly {
            severity: "NEEDS FIX",
            title: "Video Freeze Protection is NOT enabled yet".into(),
            simple_explanation: "Without this fix, watching YouTube or streaming videos can overload the CPU and freeze your screen.".into(),
            action_text: "👉 Press key [1] in this app to FIX EVERYTHING AUTOMATICALLY!".into(),
        });
    }

    if ce_channel_bug {
        anomalies.push(KernelAnomaly {
            severity: "KERNEL INFO",
            title: "Pre-Kepler Copy Engine Notice (Fermi/Tesla -22)".into(),
            simple_explanation: "A harmless Linux kernel quirk causes your GPU to use M2MF for memory copies. Does not freeze the PC.".into(),
            action_text: "Official kernel fix submitted upstream by Munique Feitoza.".into(),
        });
    }

    let mut pstates = Vec::new();
    let mut active_pstate = "Default Mode (run `sudo nouveau-boost` to switch GPU speed)".to_string();
    if let Some(pstate_raw) = read_trimmed("/sys/kernel/debug/dri/0/pstate") {
        for line in pstate_raw.lines() {
            if line.contains('*') || line.starts_with("AC:") || line.starts_with("DC:") {
                active_pstate = line.trim().to_string();
            }
            pstates.push(line.trim().to_string());
        }
    }

    GpuTelemetry {
        pci_slot,
        pci_id,
        chip_name,
        codename,
        arch_family,
        bios_version,
        vram_mib,
        pcie_speed,
        pcie_width,
        temp_c,
        temp_max_c,
        temp_crit_c,
        core_mv,
        core_min_mv,
        core_max_mv,
        fan_pwm,
        fan_mode,
        glamor_accel,
        vaapi_render_node,
        browser_vaapi_tuned,
        all_fw_present,
        falcon_fw_files,
        pstates,
        active_pstate,
        buffer_copy_engine,
        ce_channel_bug,
        kernel_anomalies: anomalies,
    }
}

